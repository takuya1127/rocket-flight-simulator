with model_tabs[2]:
    st.subheader("標準大気モデル")

    st.markdown(
        """
        高度から大気状態を計算し、
        空気抵抗やMach数の計算へ利用しています。

        現在計算している値：

        - 気温
        - 気圧
        - 空気密度
        - 音速

        現在は高度帯によって計算式を切り替える
        簡易標準大気モデルです。
        """
    )


# ========================================
# 空気抵抗
# ========================================

with model_tabs[3]:
    st.subheader("空気抵抗と動圧")

    st.markdown(
        """
        ロケットの進行方向と反対向きに
        空気抵抗が働くものとして計算しています。
        """
    )

    st.markdown("### 空気抵抗")

    st.latex(
        r"D=\frac{1}{2}\rho C_D A v^2"
    )

    st.markdown(
        """
        - `ρ`：空気密度
        - `Cᴅ`：抗力係数
        - `A`：基準断面積
        - `v`：対気速度
        """
    )

    st.markdown("### 動圧")

    st.latex(
        r"q=\frac{1}{2}\rho v^2"
    )

    st.markdown(
        """
        上昇中の最大動圧をMax Qとして記録しています。
        """
    )


# ========================================
# 推進
# ========================================

with model_tabs[4]:
    st.subheader("エンジン・推進モデル")

    st.markdown(
        """
        推進系の計算は `EngineCalculator` が担当しています。

        現在は次の要素をモデル化しています。

        - エンジン燃焼状態
        - 推力のX・Y方向分解
        - 推進剤流量
        - 燃料消費
        - 比推力
        - 推力重量比
        - 時間による推力変化
        """
    )

    st.markdown("### 推力曲線")

    st.markdown(
        """
        現在の入力推力は「最大推力」として扱います。

        燃焼中は次の3段階で推力を変化させています。

        1. 点火直後の推力立ち上がり
        2. 定常燃焼
        3. 燃焼終了前の推力減衰

        推進剤流量も推力割合に連動して変化します。
        """
    )

    st.markdown("### 推進剤流量")

    st.latex(
        r"\dot{m}=\frac{m_p}{t_{\mathrm{effective}}}"
    )

    st.markdown(
        """
        推力立ち上がり・減衰を考慮し、
        燃焼期間全体で推進剤を消費するよう
        最大推進剤流量を補正しています。
        """
    )

    st.markdown("### 比推力")

    st.latex(
        r"I_{sp}=\frac{F}{\dot{m}g_0}"
    )

    st.markdown(
        """
        比推力は、推進剤をどれだけ効率よく
        推力へ変換できるかを表す指標として扱っています。
        """
    )

    st.markdown("### 推力重量比")

    st.latex(
        r"\frac{T}{W}=\frac{F}{mg}"
    )

    st.markdown(
        """
        機体質量と重力が飛行中に変化するため、
        推力重量比も時系列で計算しています。

        今後はこの値を利用して、
        発射台保持と実際のリフトオフ判定を実装します。
        """
    )


