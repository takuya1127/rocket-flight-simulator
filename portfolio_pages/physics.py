import streamlit as st


st.title("📐 Physics & Models")

st.caption(
    "シミュレーションに使用している物理モデルと、"
    "現在の簡略化条件を整理するページです。"
)


# ========================================
# 現在のモデル
# ========================================

st.header("Implemented Models")

model_tabs = st.tabs(
    [
        "運動",
        "重力",
        "大気",
        "空気抵抗",
        "推進",
    ]
)


# ========================================
# 運動
# ========================================

with model_tabs[0]:
    st.subheader("2次元運動")

    st.markdown(
        """
        ロケットの位置と速度を、
        一定の時間刻みで更新しています。

        現在はX方向・Y方向の2次元平面で飛行を計算します。
        """
    )

    st.code(
        """
velocity_x += acceleration_x * time_step
velocity_y += acceleration_y * time_step

position_x += velocity_x * time_step
position_y += velocity_y * time_step
        """,
        language="python",
    )

    st.markdown(
        """
        現在の飛行方向は、X・Y方向速度から求めています。
        """
    )

    st.latex(
        r"\theta=\mathrm{atan2}(v_y,v_x)"
    )


# ========================================
# 重力
# ========================================

with model_tabs[1]:
    st.subheader("高度に応じた重力")

    st.markdown(
        """
        地表で重力加速度を固定せず、
        地球中心からロケットまでの距離に応じて変化させています。

        地球は完全な球として近似しています。
        """
    )

    st.latex(
        r"g(h)=g_0\left(\frac{R}{R+h}\right)^2"
    )

    st.markdown(
        """
        - `g₀`：地表付近の標準重力加速度
        - `R`：地球半径
        - `h`：地表からの高度
        """
    )


